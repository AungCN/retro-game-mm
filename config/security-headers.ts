// Single source of truth for HTTP security headers.
// Used by the Vite dev/preview servers (vite.config.ts) and written to dist/_headers for static hosts
// that support that format (Cloudflare Pages, Netlify). See docs/quality/SECURITY_GUIDELINES.md.

export const EMULATOR_PATH_PREFIX = '/emulator/';

/** Headers on every response: cross-origin isolation and general hardening. */
export const baseHeaders: Record<string, string> = {
  'Cross-Origin-Opener-Policy': 'same-origin',
  'Cross-Origin-Embedder-Policy': 'require-corp',
  'Cross-Origin-Resource-Policy': 'same-origin',
  'X-Content-Type-Options': 'nosniff',
  'Referrer-Policy': 'no-referrer',
  'Permissions-Policy':
    'camera=(), microphone=(), geolocation=(), payment=(), usb=(), serial=(), hid=(), bluetooth=(), midi=(), display-capture=(), gamepad=(self), fullscreen=(self)',
};

function csp(directives: Record<string, string[]>): string {
  return Object.entries(directives)
    .map(([k, v]) => `${k} ${v.join(' ')}`)
    .join('; ');
}

/** Platform shell: strict. `devStyles` relaxes style-src only for the Vite dev server, which injects CSS with <style> tags. */
export function shellCsp(devStyles = false): string {
  return csp({
    'default-src': ["'self'"],
    'script-src': ["'self'"],
    'style-src': devStyles ? ["'self'", "'unsafe-inline'"] : ["'self'"],
    'img-src': ["'self'", 'data:', 'blob:'],
    'font-src': ["'self'"],
    'connect-src': ["'self'"],
    'worker-src': ["'self'"],
    'manifest-src': ["'self'"],
    'media-src': ["'self'"],
    'frame-src': ["'self'"],
    'object-src': ["'none'"],
    'base-uri': ["'none'"],
    'form-action': ["'none'"],
    'frame-ancestors': ["'none'"],
  });
}

/**
 * Emulator frame documents only (DEC-004). The outer frame (/emulator/frame.html) is same-origin; it creates an inner
 * sandboxed srcdoc frame (opaque origin) that inherits this policy. EmulatorJS 4.2.3 needs:
 * - 'unsafe-eval': its 7-Zip/zip extractors use eval
 * - blob: in script-src, style-src and connect-src: its files and the core's WASM are loaded from blob: URLs
 * - 'unsafe-inline' styles: its UI sets inline style attributes
 * - the inner bootstrap script, allowed only by its exact SHA-256 hash (no 'unsafe-inline' for scripts)
 * connect-src stays 'self' + blob:, which blocks EmulatorJS's update check and its CDN core fallback.
 */
export function emulatorCsp(innerScriptHash: string): string {
  return csp({
    'default-src': ["'self'"],
    'script-src': ["'self'", "'wasm-unsafe-eval'", "'unsafe-eval'", 'blob:', `'sha256-${innerScriptHash}'`],
    'style-src': ["'self'", "'unsafe-inline'", 'blob:'],
    'img-src': ["'self'", 'data:', 'blob:'],
    'font-src': ["'self'", 'data:'],
    'connect-src': ["'self'", 'blob:'],
    'worker-src': ["'self'", 'blob:'],
    'media-src': ["'self'", 'blob:'],
    'object-src': ["'none'"],
    'base-uri': ["'none'"],
    'form-action': ["'none'"],
    'frame-ancestors': ["'self'"],
  });
}

export function headersFor(pathname: string, dev: boolean, innerScriptHash: string): Record<string, string> {
  if (pathname.startsWith(EMULATOR_PATH_PREFIX) && (pathname.endsWith('.html') || pathname.endsWith('/'))) {
    return { ...baseHeaders, 'Content-Security-Policy': emulatorCsp(innerScriptHash) };
  }
  return { ...baseHeaders, 'Content-Security-Policy': shellCsp(dev) };
}

/**
 * Cloudflare Pages `_headers` file contents. A URL matching several rules receives all of them, and
 * repeated header names are combined, so the emulator rule first detaches (`! Name`) the shell's CSP before
 * setting its own. Verify on a preview deploy before relying on it (ADR-0001).
 */
export function staticHostHeadersFile(innerScriptHash: string): string {
  const lines = (h: Record<string, string>) => Object.entries(h).map(([k, v]) => `  ${k}: ${v}`);
  return [
    '# Generated by vite.config.ts from config/security-headers.ts. Do not edit by hand.',
    '/*',
    ...lines({ ...baseHeaders, 'Content-Security-Policy': shellCsp(false), 'Strict-Transport-Security': 'max-age=31536000' }),
    '',
    `${EMULATOR_PATH_PREFIX}frame.html`,
    '  ! Content-Security-Policy',
    ...lines({ 'Content-Security-Policy': emulatorCsp(innerScriptHash) }),
    '',
  ].join('\n');
}
